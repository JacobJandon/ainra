#!/usr/bin/env node
// SPDX-License-Identifier: Apache-2.0 OR MIT
//
// make link-e2e — AINRA Link, live: the key an agent already signs with, attributed and revoked (D-078).
//
// An operator's agents already sign their requests as a SIGNATURE AGENT (the Web Bot Auth profile: Ed25519 keys in a
// directory at the operator's origin). Nothing else changes for them. The operator links those same keys to its AINRA
// passport, once, with each key's own consent. An origin then reads every request twice:
//
//   * an independent open-source signature-agent verifier answers "this key signed it";
//   * AINRA Link answers "this key acts for operator X under passport P, and that is still true" — from the
//     registrar's link index and signed status list, fetched whole and checked offline.
//
//   1. the operator: a passport from the live registrar
//   2. two signature-agent keys, in the operator's published directory
//   3. each key signs its consent; the registrar links both, and logs each link
//   4. an origin that reads both: signed requests by either key → valid, and AINRA names the operator
//   5. a key nobody linked → the signature verifies; AINRA: not linked
//   6. revoke key A (`link`) → the signature-agent reader still accepts it; AINRA refuses A, keeps accepting B
//   7. A turns out to have been stolen → the revocation is upgraded to `compromise` with `suspect_since`
//   8. suspend the operator → every link refuses, though nothing about the keys changed
//   9. every revocation is in the registrar's log
//
// TEST-ROOT, loopback, http (the profile requires https in deployment). It proves the mechanism; it is not evidence
// that any operator runs it.
//
// WITNESS: could this observe a failure? Yes — every step asserts both readers' answers, step 4 is the positive
// control for AINRA, and step 5 is the negative control: a valid signature that AINRA must not attribute.

import http from "node:http";
import { readFileSync } from "node:fs";
import { sign, verify, parseSignatureAgentHeader, HTTP_MESSAGE_SIGNATURES_DIRECTORY } from "web-bot-auth";
import { signerFromJWK, verifierFromJWK } from "web-bot-auth/crypto";
import { appendSignature } from "http-message-sig";
import { Verifier, jwkThumbprintEd25519, linkPopSigningBytes, linkFromIndex } from "../../packages/sdk-ts/dist/index.js";
import { b64uDecode, b64uEncode } from "../../packages/sdk-ts/dist/crypto.js";

const REG = process.env.AINRA_REGISTRAR ?? "http://127.0.0.1:4970";
const ART = process.env.AINRA_ARTIFACTS ?? "http://127.0.0.1:8091";
const now = () => Math.floor(Date.now() / 1000);

let bad = 0;
const ok = (m) => console.log(`  ok    ${m}`);
const fail = (m) => { console.error(`  ✗     ${m}`); bad = 1; };
const step = (m) => console.log(`\n${m}`);
async function j(url, init) {
  const r = await fetch(url, init);
  const t = await r.text();
  let body; try { body = JSON.parse(t); } catch { body = t; }
  return { status: r.status, body };
}

try { await fetch(`${REG}/accreditation`, { signal: AbortSignal.timeout(3000) }); }
catch { console.error(`link-e2e: no live registrar at ${REG} — run \`make live-up\` first`); process.exit(2); }
// Linking and revoking are operator writes. The token was generated by `make live-up`, is kept 0600 in live/, and
// goes into a request header only — never onto stdout.
let TOKEN;
try { TOKEN = readFileSync(new URL("../../live/.issue-token", import.meta.url), "utf8").trim(); }
catch { console.error("link-e2e: live/.issue-token missing — start the registrar with `make live-up`"); process.exit(2); }
const write = (path, body) => j(`${REG}${path}`, {
  method: "POST", headers: { authorization: `Bearer ${TOKEN}`, "content-type": "application/json" }, body: JSON.stringify(body),
});

// ── 1 · the operator's passport ──────────────────────────────────────────────────────────────────────────────────
step("1 · the operator: a passport from the live registrar");
const issued = await j(`${REG}/demo/issue`, { method: "POST", body: JSON.stringify({ operator: "specimen", lineage: "linked" }) });
if (issued.status !== 200) { fail(`issue failed: ${issued.status} ${JSON.stringify(issued.body)}`); process.exit(1); }
const passport = issued.body;
const directory = (await j(`${ART}/directory.json`)).body;
const roots = (await j(`${ART}/roots.json`)).body;
// F1: the strictest class. A revocation must reach this gate within thirty seconds.
const gate = Verifier.fromDirectoryB64(directory, roots.root_ed25519, roots.root_slh, "F1");
if (!gate) { fail("could not build a verifier from the published directory"); process.exit(1); }
ok(`${passport.sub}`);

// ── 2 · the operator's signature-agent keys, in its published directory ────────────────────────────────────────
step("2 · the operator's agents sign as signature agents: two Ed25519 keys in its published directory");
async function agentKey() {
  const k = await crypto.subtle.generateKey({ name: "Ed25519" }, true, ["sign", "verify"]);
  const jwk = await crypto.subtle.exportKey("jwk", k.privateKey);
  return { k, jwk, signer: await signerFromJWK({ ...jwk, alg: "EdDSA" }), x: b64uDecode(jwk.x), tp: jwkThumbprintEd25519(b64uDecode(jwk.x)) };
}
const A = await agentKey(), B = await agentKey(), C = await agentKey();
const published = [A, B, C].map((a) => ({ kty: "OKP", crv: "Ed25519", x: a.jwk.x, use: "sig", nbf: now() - 60, exp: now() + 3600 }));
const dirServer = http.createServer((req, res) => {
  if (req.url !== HTTP_MESSAGE_SIGNATURES_DIRECTORY) { res.statusCode = 404; res.end(); return; }
  res.setHeader("content-type", "application/http-message-signatures-directory+json");
  res.setHeader("cache-control", "max-age=300");
  res.end(JSON.stringify({ keys: published }));
});
await new Promise((r) => dirServer.listen(0, "127.0.0.1", r));
const AGENT_URI = `http://127.0.0.1:${dirServer.address().port}`;
ok(`${AGENT_URI}${HTTP_MESSAGE_SIGNATURES_DIRECTORY} · keys A ${A.tp.slice(0, 10)}…  B ${B.tp.slice(0, 10)}…  C ${C.tp.slice(0, 10)}… (C is never linked)`);

// ── 3 · link A and B, each with its own consent ──────────────────────────────────────────────────────────────────
step("3 · each key signs its consent; the registrar links it to the passport and logs the link");
const sizeBefore = (await j(`${REG}/links`)).body.checkpoint.size;
const nbf = passport.nbf, exp = Math.min(passport.exp, now() + 3600);
for (const [name, a] of [["A", A], ["B", B]]) {
  const pop = new Uint8Array(await crypto.subtle.sign({ name: "Ed25519" }, a.k.privateKey, linkPopSigningBytes(passport.registrar, passport.sub, a.tp, nbf)));
  const r = await write("/link", { passport: passport.sub, key: a.jwk.x, pop: b64uEncode(pop), nbf, exp });
  r.status === 200 && r.body.thumbprint === a.tp ? ok(`key ${name} linked · log leaf ${r.body.leaf_index}`) : fail(`link ${name}: ${r.status} ${JSON.stringify(r.body)}`);
}
{
  // The consent is the key's own: B's signature cannot link A.
  const pop = new Uint8Array(await crypto.subtle.sign({ name: "Ed25519" }, B.k.privateKey, linkPopSigningBytes(passport.registrar, passport.sub, C.tp, nbf)));
  const r = await write("/link", { passport: passport.sub, key: C.jwk.x, pop: b64uEncode(pop), nbf, exp });
  r.status === 400 && /holder proof/.test(r.body.error ?? "") ? ok(`linking C with B's signature as its consent → refused: ${r.body.error.split(":")[0]}`) : fail(`C with B's consent: ${r.status} ${JSON.stringify(r.body)}`);
}

// ── 4 · the origin: both readers on every request ────────────────────────────────────────────────────────────────
step("4 · an origin reads every request twice: the signature-agent verifier, then AINRA Link");
const dirCache = new Map();
async function keysAt(uri) {
  const hit = dirCache.get(uri);
  if (hit && hit.until > now()) return hit.keys;
  const r = await fetch(new URL(HTTP_MESSAGE_SIGNATURES_DIRECTORY, uri));
  const { keys } = await r.json();
  dirCache.set(uri, { keys, until: now() + Number(/max-age=(\d+)/.exec(r.headers.get("cache-control") ?? "")?.[1] ?? 0) });
  return keys;
}
/** The signature-agent reader: which directory key, if any, signed this request. */
async function signedBy(request) {
  const header = request.headers.get("signature-agent");
  if (!header) return null;
  for (const { label } of parseSignatureAgentHeader(header).entries) {
    let x = null;
    try {
      await verify(request, {
        label,
        resolver: async (profile) => {
          for (const k of await keysAt(profile.signatureAgent.uri)) {
            const v = await verifierFromJWK(k);
            if (v.keyid === profile.keyid && (k.exp === undefined || k.exp > now())) { x = k.x; return v; }
          }
          throw new Error("keyid not in that directory");
        },
      });
      return x;
    } catch (e) { if (process.env.LINK_DEBUG) console.error("verify:", e.cause?.message ?? e.message); }
  }
  return null;
}
const origin = http.createServer(async (req, res) => {
  const headers = new Headers();
  for (let i = 0; i < req.rawHeaders.length; i += 2) {
    const k = req.rawHeaders[i].toLowerCase();
    if (!["host", "connection", "content-length", "transfer-encoding"].includes(k)) headers.append(k, req.rawHeaders[i + 1]);
  }
  const x = await signedBy(new Request(`http://${req.headers.host}${req.url}`, { method: req.method, headers }));
  res.setHeader("x-signature-agent", x ? "valid" : "invalid");
  if (!x) { res.statusCode = 401; res.end(); return; }
  // AINRA Link: the whole index and the signed status list, fetched as any mirror could serve them, checked here.
  const [index, publication] = await Promise.all([j(`${REG}/links`).then((r) => r.body), j(`${REG}/status-list`).then((r) => r.body)]);
  const key = b64uDecode(x);
  const link = linkFromIndex(index, publication, jwkThumbprintEd25519(key));
  if (!link) { res.statusCode = 403; res.setHeader("x-ainra-reason", "not_linked"); res.end(); return; }
  const v = gate.verifyLink(link, key, now(), "demo:specimen");
  if (v.verdict === "valid") { res.statusCode = 200; res.setHeader("x-ainra-operator", v.operator); res.setHeader("x-ainra-passport", v.passport); }
  else { res.statusCode = 403; res.setHeader("x-ainra-reason", v.reason); }
  res.end();
});
await new Promise((r) => origin.listen(0, "127.0.0.1", r));
const url = `http://127.0.0.1:${origin.address().port}/orders`;
async function send(a) {
  // The profile covers the signature-agent header, so it is on the request before signing, not added after.
  const h = new Headers({ "signature-agent": `sig1="${AGENT_URI}"` });
  const f = await sign(new Request(url, { headers: h }), { signer: a.signer, label: "sig1", expires: new Date((now() + 300) * 1000) });
  const r = await fetch(url, { headers: appendSignature(h, f) });
  return { status: r.status, agent: r.headers.get("x-signature-agent"), reason: r.headers.get("x-ainra-reason"), operator: r.headers.get("x-ainra-operator"), passport: r.headers.get("x-ainra-passport") };
}
const both = (r) => `signature agent: ${r.agent} · AINRA: ${r.status}${r.operator ? " operator " + r.operator : ""}${r.reason ? " " + r.reason : ""}`;
for (const [name, a] of [["A", A], ["B", B]]) {
  const r = await send(a);
  r.status === 200 && r.agent === "valid" && r.operator === "specimen" && r.passport === passport.sub
    ? ok(`signed by ${name} → ${both(r)}`) : fail(`signed by ${name}: ${both(r)}`);
}

// ── 5 · the negative control ─────────────────────────────────────────────────────────────────────────────────────
step("5 · a key in the operator's directory that nobody linked");
{
  const r = await send(C);
  r.status === 403 && r.agent === "valid" && r.reason === "not_linked"
    ? ok(`signed by C → ${both(r)} — a valid signature is not, by itself, an accountable operator`) : fail(`signed by C: ${both(r)}`);
}

// ── 6 · revoke one key ───────────────────────────────────────────────────────────────────────────────────────────
step("6 · revoke key A's link");
{
  const rv = await write("/link/revoke", { thumbprint: A.tp, kind: "link" });
  rv.status === 200 ? ok(`A revoked (kind link) · log leaf ${rv.body.leaf_index}`) : fail(`revoke A: ${rv.status} ${JSON.stringify(rv.body)}`);
  const ra = await send(A), rb = await send(B);
  ra.status === 403 && ra.reason === "revoked" && ra.agent === "valid"
    ? ok(`signed by A → ${both(ra)} — the signature-agent reader has no revocation to consult`) : fail(`A after revocation: ${both(ra)}`);
  rb.status === 200 && rb.operator === "specimen" ? ok(`signed by B → ${both(rb)} — one key retired, the others untouched`) : fail(`B after A's revocation: ${both(rb)}`);
}

// ── 7 · the theft is found later ─────────────────────────────────────────────────────────────────────────────────
step("7 · A turns out to have been stolen: upgrade the revocation to a compromise");
{
  const rv = await write("/link/revoke", { thumbprint: A.tp, kind: "compromise", suspect_since: nbf + 1 });
  rv.status === 200 && rv.body.kind === "compromise" && rv.body.suspect_since === nbf + 1
    ? ok(`A: compromise, suspect since ${new Date((nbf + 1) * 1000).toISOString()} — actions signed by A after that are not the operator's`)
    : fail(`compromise A: ${rv.status} ${JSON.stringify(rv.body)}`);
  const down = await write("/link/revoke", { thumbprint: A.tp, kind: "link" });
  down.status === 400 ? ok(`downgrading it back to a plain revocation → refused`) : fail(`downgrade: ${down.status}`);
}

// ── 8 · suspend the operator ─────────────────────────────────────────────────────────────────────────────────────
step("8 · suspend the operator");
{
  const rv = await write("/link/revoke", { thumbprint: B.tp, kind: "operator" });
  rv.status === 200 ? ok(`operator suspended through B's link`) : fail(`suspend: ${rv.status} ${JSON.stringify(rv.body)}`);
  const rb = await send(B);
  rb.status === 403 && rb.reason === "revoked" && rb.agent === "valid"
    ? ok(`signed by B → ${both(rb)} — nothing about the key changed; the operator behind it did`) : fail(`B after suspension: ${both(rb)}`);
  const pv = (await j(`${REG}/verify?sub=${encodeURIComponent(passport.sub)}`)).body;
  pv.verdict?.reason === "revoked" ? ok(`and the passport itself → revoked`) : fail(`passport after suspension: ${JSON.stringify(pv)}`);
}

// ── 9 · the log ──────────────────────────────────────────────────────────────────────────────────────────────────
step("9 · the log");
{
  const idx = (await j(`${REG}/links`)).body;
  const ours = idx.links.filter((l) => l.passport === passport.sub);
  const kinds = ours.map((l) => `${l.thumbprint === A.tp ? "A" : "B"}:${l.revocations.map((r) => r.kind).join("→")}`).sort();
  const grew = idx.checkpoint.size - sizeBefore;
  // Two links + A's revocation + A's compromise + the suspension, which reaches EVERY link of the operator (A's
  // too) = 6 entries at least. Other writers on the same registrar may add more; never fewer.
  grew >= 6 && kinds.join(" ") === "A:link→compromise→operator B:operator"
    ? ok(`${grew} new log entries; the index says ${kinds.join(", ")}`) : fail(`log grew ${grew}; index says ${kinds.join(", ")}`);
}

dirServer.close(); origin.close();
console.log(bad ? "\nLINK E2E FAILED" : "\nLINK E2E OK: a key the agent already had, attributed to its operator and revoked — live");
process.exit(bad);
